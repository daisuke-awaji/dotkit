// Generates CSS glyph rules and TS names from the dot-matrix bitmaps (single source of truth):
//   icons/icons.json   7x7 icons        -> .dk-icon--{name}
//   icons/glyphs.json  5x7 characters   -> .dk-glyph--{slug}   (used by .dk-digits)
// Any rectangular bitmap works; each set declares its size so the generator can validate it.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const load = (f) => JSON.parse(readFileSync(resolve(root, f), "utf8"));

/** Class-name slug for a glyph character. */
const slugs = { ":": "colon", ".": "dot", ",": "comma", "-": "minus", "+": "plus", "%": "percent", "/": "slash", " ": "space" };
const slug = (c) => slugs[c] ?? c;

const sets = [
  { file: "icons/icons.json", prefix: "dk-icon--", w: 7, h: 7, name: (k) => k },
  { file: "icons/glyphs.json", prefix: "dk-glyph--", w: 5, h: 7, name: slug },
];

function shadows(rows) {
  const out = [];
  rows.forEach((row, y) =>
    [...row].forEach((c, x) => {
      if (c === "#") out.push(`calc(var(--dk-icon-step)*${x}) calc(var(--dk-icon-step)*${y}) 0 0 currentColor`);
    }),
  );
  return out.length ? out.join(", ") : "none";
}

const css = ["/* AUTO-GENERATED by scripts/build-icons.mjs — do not edit. */", "@layer dotkit.utilities {"];
const data = {};
for (const set of sets) {
  data[set.file] = load(set.file);
  for (const [key, rows] of Object.entries(data[set.file])) {
    if (rows.length !== set.h || rows.some((r) => r.length !== set.w)) {
      throw new Error(`${set.file}: "${key}" must be a ${set.w}x${set.h} matrix`);
    }
    css.push(`  .${set.prefix}${set.name(key)}::before { box-shadow: ${shadows(rows)}; }`);
  }
}
css.push("}");
writeFileSync(resolve(root, "src/css/icons.css"), css.join("\n") + "\n");

const names = Object.keys(data["icons/icons.json"]);
const chars = Object.keys(data["icons/glyphs.json"]);
mkdirSync(resolve(root, "src/react"), { recursive: true });
writeFileSync(
  resolve(root, "src/react/icon-names.ts"),
  `// AUTO-GENERATED by scripts/build-icons.mjs — do not edit.\n` +
    `export const iconNames = ${JSON.stringify(names, null, 2)} as const;\n\n` +
    `export type IconName = (typeof iconNames)[number];\n\n` +
    `/** Characters available in <DotDigits> / .dk-glyph--{slug}. */\n` +
    `export const glyphChars = ${JSON.stringify(chars)} as const;\n\n` +
    `export type GlyphChar = (typeof glyphChars)[number];\n\n` +
    `/** Character -> class-name slug (e.g. ":" -> "colon"). */\n` +
    `export const glyphSlug: Record<GlyphChar, string> = ${JSON.stringify(Object.fromEntries(chars.map((c) => [c, slug(c)])))};\n`,
);
console.log(`icons: ${names.length} icons + ${chars.length} glyphs generated`);
