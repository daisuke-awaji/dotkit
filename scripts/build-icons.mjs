// Generates CSS glyph rules and TS icon names from icons/icons.json (single source of truth).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const icons = JSON.parse(readFileSync(resolve(root, "icons/icons.json"), "utf8"));

const css = [];
css.push("/* AUTO-GENERATED by scripts/build-icons.mjs — do not edit. */");
css.push("@layer dotkit.utilities {");
for (const [name, rows] of Object.entries(icons)) {
  if (rows.length !== 7 || rows.some((r) => r.length !== 7)) {
    throw new Error(`icon "${name}" must be a 7x7 matrix`);
  }
  const shadows = [];
  rows.forEach((row, y) =>
    [...row].forEach((c, x) => {
      if (c === "#") shadows.push(`calc(var(--dk-icon-step)*${x}) calc(var(--dk-icon-step)*${y}) 0 0 currentColor`);
    }),
  );
  css.push(`  .dk-icon--${name}::before { box-shadow: ${shadows.join(", ")}; }`);
}
css.push("}");
writeFileSync(resolve(root, "src/css/icons.css"), css.join("\n") + "\n");

const names = Object.keys(icons);
mkdirSync(resolve(root, "src/react"), { recursive: true });
writeFileSync(
  resolve(root, "src/react/icon-names.ts"),
  `// AUTO-GENERATED by scripts/build-icons.mjs — do not edit.\n` +
    `export const iconNames = ${JSON.stringify(names, null, 2)} as const;\n\n` +
    `export type IconName = (typeof iconNames)[number];\n`,
);
console.log(`icons: ${names.length} glyphs generated`);
